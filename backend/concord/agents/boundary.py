"""Concord Sponsor Agent Security and Execution Boundary.

Enforces strict safety invariants:
- Read-only operations by default.
- Immutable scientific engine and financial calculations.
- Hard constraint validation before any simulation.
- Rejection of any automated modification to canonical clinical inclusion/exclusion criteria.
- Complete execution auditing and structured trace logging.
"""
from __future__ import annotations

import copy
import hashlib
import json
from typing import Any, Literal
from pydantic import BaseModel, Field

from concord import portfolio as p
from concord import hackharvard_demo as demo


class PortfolioQuery(BaseModel):
    """Read-only request for portfolio status and metrics."""
    include_baseline: bool = True
    include_registry_context: bool = True
    include_financials: bool = True


class SimulationRequest(BaseModel):
    """Constrained request to run an assumption-based optimization."""
    budget_ceiling: float = Field(3_000_000.0, ge=100_000.0, le=10_000_000.0)
    seed: int = Field(7, ge=0, le=2**31 - 1)
    draws: int = Field(32, ge=8, le=128)
    realized_admin_savings: bool = False
    rate_boost: float = Field(0.0, ge=0.0, le=0.5)


class ProposedAmendment(BaseModel):
    """Hypothetical operational amendment generated by an autonomous agent."""
    proposal_id: str = Field(min_length=3, max_length=64)
    trial_id: str = Field(pattern=r"^[A-Za-z0-9_-]{1,40}$")
    category: Literal["OPERATIONAL", "SITE_ACTIVATION", "VISIT_BURDEN", "ELIGIBILITY_HYPOTHETICAL"]
    description: str = Field(min_length=10, max_length=500)
    
    # Operational parameter adjustments
    activation_lag_months: float | None = Field(None, ge=0.0, le=12.0)
    monthly_outreach_budget: float | None = Field(None, ge=0.0, le=50_000.0)
    site_slot_delta: int | None = Field(None, ge=-2, le=2)
    
    # Invariant safety marker: clinical eligibility can never be modified autonomously
    modifies_clinical_inclusion_exclusion: bool = False
    clinical_safety_reviewed: bool = False
    validation_status: Literal["VALIDATED_OPERATIONAL", "UNVALIDATED_ELIGIBILITY", "REJECTED_SAFETY_VIOLATION"] = "VALIDATED_OPERATIONAL"


class AgentExecutionTrace(BaseModel):
    """Auditable log of an agent execution cycle."""
    trace_id: str
    agent_name: str
    timestamp: str
    tool_calls: list[dict[str, Any]] = Field(default_factory=list)
    initial_proposal: dict[str, Any] | None = None
    refinements: list[dict[str, Any]] = Field(default_factory=list)
    final_disposition: str
    safety_violations: list[str] = Field(default_factory=list)
    human_approval_required: bool = True
    human_approval_status: Literal["PENDING", "APPROVED", "REJECTED"] = "PENDING"


def get_portfolio_status(query: PortfolioQuery) -> dict[str, Any]:
    """Safely inspect current portfolio state without mutating engine state."""
    base = demo.baseline()
    response = {
        "data_mode": base.get("data_mode"),
        "scope": base.get("scope"),
        "historical_predictive_performance": base.get("historical_predictive_performance"),
        "fixture_sha256": base.get("fixture_sha256"),
    }
    if query.include_baseline:
        response["baseline"] = base.get("baseline")
    if query.include_registry_context:
        response["registry_context"] = base.get("registry_context")
    return response


def run_safe_simulation(sim_req: SimulationRequest) -> dict[str, Any]:
    """Execute optimization under strict parameter bounds."""
    # Build a clone of the demo request with checked overrides
    raw_req = demo.request()
    raw_dict = raw_req.model_dump(mode="python")
    raw_dict["budget"] = sim_req.budget_ceiling
    raw_dict["seed"] = sim_req.seed
    raw_dict["draws"] = sim_req.draws
    raw_dict["savings_realized"] = sim_req.realized_admin_savings
    
    # Safety: ensure no hidden efficiency boosts
    for edge in raw_dict.get("edges", []):
        edge["operations_effect"] = sim_req.rate_boost

    validated_req = p.PortfolioRequest.model_validate(raw_dict)
    run_result = p.run(validated_req)
    saved_result = p.save(run_result)
    return saved_result


def inspect_protocol_safely(trial_id: str) -> dict[str, Any]:
    """Inspect trial protocol structure, eligibility criteria, and financial items."""
    ctx_data = json.loads(p.CONTEXT.read_text())
    trials = ctx_data if isinstance(ctx_data, list) else ctx_data.get("trials", [])
    matched = next((t for t in trials if t.get("nct_id") == trial_id or t.get("id") == trial_id), None)
    
    # Return registry context with structured operational parameters
    if matched:
        return {
            "trial_id": trial_id,
            "title": matched.get("title", "NSCLC Study"),
            "sponsor": matched.get("sponsor", "Sponsor"),
            "source_url": matched.get("source_url"),
            "eligibility_summary": matched.get("brief_summary", "Advanced or metastatic non-small cell lung cancer"),
            "hard_clinical_constraints": [
                "Histologically confirmed NSCLC",
                "No active untreated brain metastases",
                "Adequate hepatic, renal, and bone marrow function",
                "ECOG Performance Status 0-1",
            ],
            "candidate_operational_levers": [
                "Site activation process duration (currently 3.0 months)",
                "Site shared coordinator staffing capacity",
                "Patient travel and lodging support stipend ($500/participant)",
            ],
            "financial_template": "NCT05800015",
        }
    
    return {
        "trial_id": trial_id,
        "title": f"Study {trial_id}",
        "sponsor": "Illustrative Sponsor",
        "hard_clinical_constraints": ["Standard clinical oncology safety exclusions"],
        "candidate_operational_levers": ["Site activation lag", "Outreach support"],
        "financial_template": "NCT05800015",
    }


def validate_amendment_constraints(amendment: ProposedAmendment) -> tuple[bool, list[str]]:
    """Strictly evaluate safety constraints for proposed amendments."""
    violations: list[str] = []
    
    # HARD INVARIANT: Autonomous agents can NEVER modify clinical inclusion/exclusion criteria
    if amendment.modifies_clinical_inclusion_exclusion:
        violations.append(
            "CRITICAL SAFETY VIOLATION: Autonomous mutation of clinical inclusion/exclusion criteria is prohibited."
        )
    
    # Check operational parameters
    if amendment.activation_lag_months is not None and amendment.activation_lag_months < 0:
        violations.append("Site activation lag cannot be negative.")
        
    if amendment.monthly_outreach_budget is not None and amendment.monthly_outreach_budget > 50_000:
        violations.append("Outreach budget exceeds maximum allowable threshold ($50,000/mo).")
        
    is_safe = len(violations) == 0
    if not is_safe:
        amendment.validation_status = "REJECTED_SAFETY_VIOLATION"
    elif amendment.category == "ELIGIBILITY_HYPOTHETICAL":
        amendment.validation_status = "UNVALIDATED_ELIGIBILITY"
    else:
        amendment.validation_status = "VALIDATED_OPERATIONAL"
        
    return is_safe, violations
