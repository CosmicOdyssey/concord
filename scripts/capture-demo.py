#!/usr/bin/env python3
"""Explicitly generate a real saved rehearsal; never called by the live demo.

Run with backend/.venv/bin/python scripts/capture-demo.py from a clean code commit.
The payload preserves its actual code commit, dirty flag, source hashes and runtime.
"""
from pathlib import Path
import hashlib
import json
import os
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'backend'))
os.environ['CONCORD_DATA_DIR'] = str(ROOT/'.fleet/state/hackharvard-demo-data')
from concord import hackharvard_demo as d, portfolio as p  # noqa: E402

bundle = d.baseline()
run = d.optimize()
assert p.valid_result(run['result'])
assert run['result']['request'] == bundle['request']
run['delivery_mode'] = 'SAVED_RESULT_REPLAY'
out = ROOT/'frontend/public/demo'
out.mkdir(parents=True,exist_ok=True)
raw = json.dumps({'bundle':bundle, 'run':run},indent=2,allow_nan=False)+'\n'
(out/'saved-result.json').write_text(raw)
(out/'saved-report.html').write_text(p.report_html(run['result']).replace('<h1>', '<p><b>SAVED REHEARSAL — NOT LIVE COMPUTATION</b></p><h1>',1))
sha = hashlib.sha256(raw.encode()).hexdigest()
(ROOT/'frontend/src/demoSavedDigest.ts').write_text('// Generated by scripts/capture-demo.py. Hash of genuine saved result bytes, not an outcome.\nexport const SAVED_DEMO_SHA256 = '+repr(sha)+'\n')
print(json.dumps({'run_id':run['result']['run_id'], 'saved_file_sha256':sha,'compute_ms':run['compute_ms'],'evidence':run['result']['evidence']['commit'],'dirty':run['result']['evidence']['dirty']}))
